// in the manner of Susan Kare's original Macintosh icons. "#" is ink,
// "+" the tone (the same colour, lighter), "." empty. One drawing pixel is
// one pixel of the pixel font at 16px, two at 32 and three (a scenery
// pixel) at 48, so icons, labels and landscapes share a single grid.
//
// Symbols use two-pixel strokes so they hold their own beside text; things
// are outlined in one pixel with their faces in tone; every drawing keeps a
// one-pixel margin and centres on the 8,8 corner.

